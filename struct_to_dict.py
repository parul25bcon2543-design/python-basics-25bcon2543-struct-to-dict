# Convert structure/object to dictionary

class Student:
    def __init__(self, name, roll_no, course):
        self.name = name
        self.roll_no = roll_no
        self.course = course


student = Student("Rahul", 101, "Python")

student_dict = student.__dict__

print("Student Dictionary:")
print(student_dict)